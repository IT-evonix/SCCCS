<script>
    document.addEventListener("DOMContentLoaded", () => {
    const amounts = document.querySelectorAll(".project_amount");
    const totalEl = document.querySelector(".total_grants_amount .amount");

    let totalLakhs = 0;

    amounts.forEach(item => {
        let value = item.innerText.trim();

        // Handle "L" values
        if (value.includes("L")) {
        totalLakhs += parseFloat(value.replace("L", "").trim());
        }

        // If in future you add CR directly
        if (value.includes("CR")) {
        totalLakhs += parseFloat(value.replace("CR", "").trim()) * 100;
        }
    });

    // Convert Lakhs → Crores
    const totalCrores = (totalLakhs / 100).toFixed(2);

    // COUNT-UP Animation
    let current = 0;
    const target = parseFloat(totalCrores);
    const speed = 40;

    const animateTotal = () => {
        const increment = target / speed;
        if (current < target) {
        current += increment;
        totalEl.innerText = current.toFixed(2);
        requestAnimationFrame(animateTotal);
        } else {
        totalEl.innerText = target.toFixed(2);
        }
    };

    animateTotal();
    });
</script>


