                        <div class="heading">About SCCCS</div>
                        <p>Climate change is not just an environmental issue. It is fast becoming one of the defining facts of economic development in the 21st century.  It will shape investment, technology deployment, and human development around the world.</p>
                        <p>The Symbiosis Centre for Climate Change and Sustainability (SCCCS) stands at the forefront of India's response to one of humanity's most pressing challenges—climate change. Recognizing that the future trajectory of human societies depends fundamentally on our capacity to adapt, mitigate, and build resilience against climatic disruptions, SCCCS has emerged as a vital hub for climate research and action within Symbiosis International University (Deemed University).</p>
                        <p>As a megadiverse nation with extraordinary biogeographical variation and rich socio-cultural heterogeneity, India requires context-specific climate solutions that respect and build upon this diversity. While global knowledge and international collaboration remain essential, SCCCS is committed to advancing research frameworks that are deeply rooted in India's ecological realities and social complexities. The Centre recognizes that effective climate action cannot be imported wholesale from other contexts but must emerge from rigorous inquiry into local-to-regional dynamics while maintaining global relevance.</p>
                        <p>SCCCS operates at the intersection of scientific excellence, policy engagement, and societal transformation. The Centre harnesses the multidisciplinary competencies across Symbiosis International University to conduct cutting-edge interdisciplinary research, design innovative learning programs, and lead advocacy initiatives that translate knowledge into tangible climate action. Through strategic collaborations with research institutions, government agencies, industry partners, and civil society organizations, SCCCS pursues action-oriented research that bridges the gap between academic inquiry and practical implementation.</p>
                        <p>The Centre's research portfolio addresses critical dimensions of the climate crisis through rigorous scientific investigation. From examining the public health implications of urban landfills and pharmaceutical contamination in ecosystems to pioneering work on climate-induced pathogen evolution and greenhouse gas emissions from agricultural and wastewater systems, SCCCS tackles problems that connect environmental degradation with human and planetary health. The Centre's work on renewable energy transitions, sustainable urban development, and campus-scale sustainability models demonstrates a commitment to developing replicable solutions that can drive systemic change.</p>
                        <p>Beyond generating knowledge, SCCCS is dedicated to cultivating the next generation of climate leaders. Through comprehensive doctoral and post-doctoral training programs, student-centered awareness campaigns, and community engagement initiatives, the Centre is building a cadre of informed, empowered climate ambassadors equipped to lead India's sustainability transformation. By integrating research excellence with education, capacity building, and public outreach, SCCCS embodies a holistic approach to addressing the climate emergency—one that recognizes that lasting solutions require not just technological innovation but also shifts in consciousness, behavior, and institutional practice.</p>
